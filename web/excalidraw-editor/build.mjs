// Builds the offline editor page that okilum-shell embeds (#478) into
// crates/okilum-shell/assets/excalidraw-editor/. The output is committed:
// a desktop build never needs Node or the network.
//
//   npm ci --ignore-scripts && node build.mjs          rebuild the committed output
//   npm ci --ignore-scripts && node build.mjs --check  fail unless a rebuild is identical
//
// files.rs lists every served file with its media type for the Rust side, and
// SHA256SUMS lets anyone check the committed bytes without a rebuild.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import zlib from "node:zlib";

const here = path.dirname(fileURLToPath(import.meta.url));
const committed = path.resolve(here, "../../crates/okilum-shell/assets/excalidraw-editor");
const fonts = path.join(here, "node_modules/@excalidraw/excalidraw/dist/prod/fonts");
const check = process.argv.includes("--check");

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
};

function walk(dir, prefix = "") {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap((entry) => {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      return entry.isDirectory() ? walk(path.join(dir, entry.name), rel) : [rel];
    });
}

async function produce(out) {
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(path.join(out, "assets"), { recursive: true });
  await build({
    entryPoints: { editor: path.join(here, "src/main.jsx") },
    outdir: path.join(out, "assets"),
    bundle: true,
    splitting: true,
    chunkNames: "chunks/[name]-[hash]",
    format: "esm",
    target: ["es2020", "chrome100", "firefox100", "safari15"],
    minify: true,
    legalComments: "external",
    jsx: "automatic",
    define: { "process.env.NODE_ENV": '"production"', "process.env.IS_PREACT": '"false"' },
    loader: { ".woff2": "file" },
    assetNames: "[name]-[hash]",
    charset: "utf8",
    logLevel: "warning",
    conditions: ["production"],
    absWorkingDir: here,
  });
  fs.copyFileSync(path.join(here, "src/index.html"), path.join(out, "index.html"));
  fs.copyFileSync(path.join(here, "src/asset-path.js"), path.join(out, "assets/asset-path.js"));
  fs.cpSync(fonts, path.join(out, "fonts"), { recursive: true });

  // One notice file instead of esbuild's per-chunk legal comment files.
  const legal = walk(out).filter((rel) => rel.endsWith(".LEGAL.txt"));
  const notices = [
    "Third-party code in the Okilum Excalidraw editor page, as esbuild kept it.",
    "@excalidraw/excalidraw (MIT) and its fonts under fonts/ (SIL Open Font",
    "License 1.1) come from the npm package pinned in web/excalidraw-editor.",
    "",
    ...legal.flatMap((rel) => {
      const text = fs.readFileSync(path.join(out, rel), "utf8").trim();
      fs.rmSync(path.join(out, rel));
      return [`== ${rel.replace(/\.LEGAL\.txt$/, "")}`, text, ""];
    }),
  ].join("\n");
  fs.writeFileSync(path.join(out, "NOTICES.txt"), notices);

  // Text assets are stored gzip-compressed and served with
  // Content-Encoding: gzip; fonts are already compressed.
  const files = walk(out).filter((rel) => rel !== "NOTICES.txt");
  const entries = files.map((rel) => {
    const type = TYPES[path.extname(rel)];
    if (!type) throw new Error(`No media type for ${rel}`);
    if (rel.endsWith(".woff2")) return { rel, stored: rel, type, gzip: false };
    const full = path.join(out, rel);
    fs.writeFileSync(`${full}.gz`, zlib.gzipSync(fs.readFileSync(full), { level: 9 }));
    fs.rmSync(full);
    return { rel, stored: `${rel}.gz`, type, gzip: true };
  });
  const rust = [
    "// Generated by web/excalidraw-editor/build.mjs; do not edit.",
    "// (served path, media type, stored gzip-compressed, bytes)",
    "&[",
    ...entries.map(
      ({ rel, stored, type, gzip }) =>
        `    (${JSON.stringify(rel)}, ${JSON.stringify(type)}, ${gzip}, include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/assets/excalidraw-editor/${stored}")) as &[u8]),`,
    ),
    "]",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(out, "files.rs"), rust);
  const sums = walk(out)
    .filter((rel) => rel !== "SHA256SUMS")
    .map((rel) => `${createHash("sha256").update(fs.readFileSync(path.join(out, rel))).digest("hex")}  ${rel}`)
    .join("\n");
  fs.writeFileSync(path.join(out, "SHA256SUMS"), `${sums}\n`);
}

if (check) {
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "okilum-excalidraw-editor-"));
  try {
    const out = path.join(scratch, "out");
    await produce(out);
    const fresh = walk(out);
    const old = fs.existsSync(committed) ? walk(committed) : [];
    const differ = [...new Set([...fresh, ...old])].filter((rel) => {
      const a = path.join(out, rel);
      const b = path.join(committed, rel);
      return !fs.existsSync(a) || !fs.existsSync(b) || !fs.readFileSync(a).equals(fs.readFileSync(b));
    });
    if (differ.length) {
      console.error(`Committed editor build differs from a rebuild in ${differ.length} file(s):`);
      for (const rel of differ.slice(0, 20)) console.error(`  ${rel}`);
      process.exit(1);
    }
    console.log(`Editor build is reproducible: ${fresh.length} files identical.`);
  } finally {
    fs.rmSync(scratch, { recursive: true, force: true });
  }
} else {
  await produce(committed);
  console.log(`Wrote ${committed}`);
}
