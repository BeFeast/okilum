#!/usr/bin/env python3
"""Exercise setup, formatting and verification in an isolated fresh source tree.

The existing vendor Git object store seeds an unpatched clone; its working files
are never copied or modified. No Cargo build or shared target is used.
"""
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]


def run(args, root, *, success=True):
    result = subprocess.run(args, cwd=root, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, timeout=180)
    print(result.stdout, end="", flush=True)
    if (result.returncode == 0) != success:
        raise RuntimeError(f"Unexpected exit {result.returncode}: {args}")
    return result


def main():
    with tempfile.TemporaryDirectory(prefix="okilum-vendor-generation-") as temporary:
        fresh = Path(temporary)
        # Include the exact checked-out files (also usable before committing),
        # never ignored vendor output or a developer's Cargo target directory.
        files = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT)
        for name in files.decode().split("\0"):
            if not name:
                continue
            source = ROOT / name
            target = fresh / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target, follow_symlinks=False)
        vendor = fresh / "vendor/gpui-component"
        vendor.parent.mkdir()
        run(["git", "clone", "--quiet", "--shared", str(ROOT / "vendor/gpui-component"),
             str(vendor)], fresh)
        run(["bash", "scripts/vendor-setup.sh"], fresh)
        run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh)
        # Both the ordinary formatter and --all must leave generated bytes alone.
        run(["cargo", "fmt"], fresh)
        run(["cargo", "fmt", "--all"], fresh)
        run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh)
        run(["bash", "scripts/vendor-setup.sh"], fresh)
        run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh)
        # Positive control: the formatting fence must not waive real source drift.
        source = vendor / "crates/base/src/input/base/element.rs"
        source.write_text(source.read_text() + "\n// unexpected generated edit\n")
        result = run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh,
                     success=False)
        if "working tree differs from the complete patch stack" not in result.stdout:
            raise RuntimeError("Verification failed without detecting generated drift")
    print("Fresh setup/format/idempotence/verify and tamper control PASS")


if __name__ == "__main__":
    main()
