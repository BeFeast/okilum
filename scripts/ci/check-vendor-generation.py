#!/usr/bin/env python3
"""Exercise setup, formatting and verification in an isolated fresh source tree.

The existing vendor Git object store seeds an unpatched clone; its working files
are never copied or modified. No Cargo build or shared target is used.
"""
from contextlib import contextmanager
from pathlib import Path
import fcntl
import os
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]


def vendor_fmt_lock_path():
    """One lock per user on this host, shared by every slot of that user.

    Run 45007121115 pinned shards base and admission to baldr. Both entered
    cargo fmt together and each hit the 180s limit, so neither started managed
    admission. The wait is outside that limit.
    """
    override = os.environ.get("OKILUM_VENDOR_FMT_LOCK")
    if override:
        return Path(override)
    return Path.home() / ".cache" / "okilum-vendor-fmt.lock"


@contextmanager
def vendor_fmt_lock():
    path = vendor_fmt_lock_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def run(args, root, *, success=True):
    try:
        result = subprocess.run(args, cwd=root, text=True, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, timeout=180)
    except subprocess.TimeoutExpired as error:
        output = error.stdout or b""
        print(output.decode(errors="replace") if isinstance(output, bytes) else output,
              end="", flush=True)
        raise RuntimeError(f"Vendor generation command timed out after 180s: {args}") from error
    print(result.stdout, end="", flush=True)
    if (result.returncode == 0) != success:
        raise RuntimeError(f"Unexpected exit {result.returncode}: {args}")
    return result


def format_generated_clone(root):
    with vendor_fmt_lock():
        run(["cargo", "fmt"], root)
        run(["cargo", "fmt", "--all"], root)


def main():
    with tempfile.TemporaryDirectory(prefix="okilum-vendor-generation-") as temporary:
        fresh = Path(temporary)
        # Include the exact checked-out files (also usable before committing),
        # never ignored vendor output or a developer's Cargo target directory.
        files = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT)
        for name in files.decode().split("\0"):
            if not name:
                continue
            source = ROOT / name
            if source.is_symlink():
                # Preserve checkout-relative links, but never follow host paths.
                link = Path(source.readlink())
                if link.is_absolute() or not source.resolve().is_relative_to(ROOT):
                    raise RuntimeError(f"Tracked symlink escapes the source checkout: {name}")
            target = fresh / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target, follow_symlinks=False)
        vendor = fresh / "vendor/gpui-component"
        vendor.parent.mkdir()
        run(["git", "clone", "--quiet", "--shared", str(ROOT / "vendor/gpui-component"),
             str(vendor)], fresh)
        run(["bash", "scripts/vendor-setup.sh"], fresh)
        run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh)
        # Both the ordinary formatter and --all must leave generated bytes alone.
        # The lock is per host, so a sibling slot waits here and then gets the
        # full 180s for each fmt command.
        format_generated_clone(fresh)
        run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh)
        run(["bash", "scripts/vendor-setup.sh"], fresh)
        run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh)
        # Positive control: the formatting fence must not waive real source drift.
        source = vendor / "crates/base/src/input/base/element.rs"
        source.write_text(source.read_text() + "\n// unexpected generated edit\n")
        result = run(["bash", "scripts/vendor-setup.sh", "--verify"], fresh,
                     success=False)
        if "working tree differs from the complete patch stack" not in result.stdout:
            raise RuntimeError("Verification failed without detecting generated drift")
    print("Fresh setup/format/idempotence/verify and tamper control PASS")


if __name__ == "__main__":
    main()
