"""#653: the vendor lock gets our gpui-pre family and keeps everything else."""
from pathlib import Path
import sys
import tomllib
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vendor_gpui_lock as lock  # noqa: E402

REG = "registry+https://github.com/rust-lang/crates.io-index"


def package(name, version, *dependencies, source=REG):
    entry = {"name": name, "version": version}
    if source:
        entry["source"] = source
        entry["checksum"] = f"{name}-{version}".encode().hex()
    if dependencies:
        entry["dependencies"] = list(dependencies)
    return entry


ROOT = {"version": 4, "package": [
    package("gpui-pre", "0.3.3", "gpui-pre-util", "smallvec 1.15.0", source=None),
    package("gpui-pre-util", "0.3.3", "newdep"),
    package("newdep", "2.0.0"),
    package("okilum-core", "0.1.0", "gpui-pre", source=None),
    package("smallvec", "1.15.0"),
]}
VENDOR = {"version": 4, "package": [
    package("crypto-bigint", "0.7.5"),
    package("gpui-base", "0.6.0", "gpui-pre", "crypto-bigint", source=None),
    package("gpui-pre", "0.3.2", "gpui-pre-util"),
    package("gpui-pre-util", "0.3.2"),
    package("gpui-pre-reqwest-client", "0.3.2", "gpui-pre-util"),
    package("smallvec", "1.15.0"),
]}


class VendorGpuiLock(unittest.TestCase):
    def test_family_is_ours_and_vendor_only_packages_stay(self):
        merged = {(p["name"], p["version"]): p for p in lock.merge(ROOT, VENDOR)}
        self.assertIn(("gpui-pre", "0.3.3"), merged)
        self.assertIn(("gpui-pre-util", "0.3.3"), merged)
        self.assertNotIn(("gpui-pre", "0.3.2"), merged)
        self.assertNotIn(("gpui-pre-util", "0.3.2"), merged)
        # A vendor-only family crate pinned to the old family is left to cargo.
        self.assertFalse(any(name == "gpui-pre-reqwest-client" for name, _ in merged))
        # Vendor-only packages (the offline resolution CI needs) are kept.
        self.assertIn(("crypto-bigint", "0.7.5"), merged)
        self.assertIn(("gpui-base", "0.6.0"), merged)
        # The family's own dependencies come along; our unrelated crates do not.
        self.assertIn(("newdep", "2.0.0"), merged)
        self.assertNotIn(("okilum-core", "0.1.0"), merged)
        self.assertNotIn("source", merged[("gpui-pre", "0.3.3")])

    def test_dump_round_trips_through_toml(self):
        packages = lock.merge(ROOT, VENDOR)
        text = lock.dump(4, packages)
        self.assertTrue(text.startswith("# This file is automatically @generated by Cargo."))
        self.assertEqual(tomllib.loads(text), {"version": 4, "package": packages})


if __name__ == "__main__":
    unittest.main()
