#!/usr/bin/env python3
"""Give the vendor workspace our gpui-pre family for its own tests (#653).

    vendor_gpui_lock.py ROOT_LOCK VENDOR_LOCK

Okilum ships gpui-pre 0.3.3 (patched, Cargo.toml [patch.crates-io], #2803) and
the vendor patch stack uses its API, while vendor/gpui-component/Cargo.lock
pins the crates.io family one release older, with exact cross-requirements, so
cargo cannot move one crate of the family. This rewrites VENDOR_LOCK in place:
every gpui-pre* entry is replaced by our lock's entries (vendor-only ones are
dropped for cargo to resolve), and any package those
entries need that the vendor lock lacks is taken from our lock too. Every other
vendor entry stays, so an offline build resolves exactly as before. Callers
restore the original vendor lock afterwards.
"""
import sys
import tomllib
from pathlib import Path


def family(name):
    return name.startswith("gpui-pre")


def key(package):
    return package["name"], package["version"]


def merge(root, vendor):
    """The vendor lock's packages with our gpui-pre family and its closure.
    Family crates only the vendor uses (e.g. gpui-pre-reqwest-client) are left
    out: their exact pins on the old family would conflict, and cargo resolves
    the one release that matches ours."""
    names = {p["name"] for p in root["package"] if family(p["name"])}
    out = {key(p): p for p in vendor["package"] if not family(p["name"])}
    out.update({key(p): p for p in root["package"] if p["name"] in names})
    by_name = {}
    for package in root["package"]:
        by_name.setdefault(package["name"], []).append(package)
    pending = [p for p in out.values() if p["name"] in names]
    while pending:
        package = pending.pop()
        for dependency in package.get("dependencies", []):
            name, *rest = dependency.split(" ")
            version = rest[0] if rest else None
            if any(n == name and (version is None or v == version) for n, v in out):
                continue
            for candidate in by_name.get(name, []):
                if version is None or candidate["version"] == version:
                    out[key(candidate)] = candidate
                    pending.append(candidate)
    return [out[k] for k in sorted(out)]


def dump(version, packages):
    """Cargo.lock text in Cargo's own layout."""
    lines = ["# This file is automatically @generated by Cargo.",
             "# It is not intended for manual editing.", f"version = {version}"]
    for package in packages:
        lines += ["", "[[package]]"]
        for field in ("name", "version", "source", "checksum"):
            if field in package:
                lines.append(f'{field} = "{package[field]}"')
        if package.get("dependencies"):
            lines.append("dependencies = [")
            lines += [f' "{dependency}",' for dependency in package["dependencies"]]
            lines.append("]")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    root = tomllib.loads(Path(sys.argv[1]).read_text())
    target = Path(sys.argv[2])
    vendor = tomllib.loads(target.read_text())
    target.write_text(dump(vendor.get("version", 4), merge(root, vendor)))


if __name__ == "__main__":
    main()
