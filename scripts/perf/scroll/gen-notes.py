#!/usr/bin/env python3
"""The notes the scroll probe uses (#1290, #1004): the same bytes on every host.

    gen-notes.py OUTDIR            write the notes and manifest.json into OUTDIR
    gen-notes.py OUTDIR --check    also compare them with scripts/perf/scroll/manifest.json

big-24k.md      the #1290 note, byte for byte as scripts/windows/qa-vm/scroll-frametime.ps1
                writes it (CRLF, 1,500 sections, 24,000 lines), so a run here is comparable with
                the 12.6 fps that issue measured.
Long-10k.md     the #1004 notes: 10,000 lines / 872 KB / 436 headings, and
Tiny-20.md      the first 20 lines of Long-LP-700.md: a control that nothing scrolls slowly because of its size.
big-head-320.md the first 20 sections (320 lines) of big-24k.md: the same blocks on screen as the
                24k note, so a frame that costs more on big-24k.md than here grows with the note's
                length, not with what is drawn (the Linux CI guard, scroll/budget.py).
Long-LP-700.md  700 lines / 63 KB / 32 headings (under Live Preview's size limit). These are the
                files the Hedva vault held, regenerated by a port of that vault's generator
                (tools/gen-vault.py of the Mac QA kit: seed 42, 2,000 notes first, then these
                two), so the Hedva numbers of the #1004 comments stay comparable.
The probe checks every note's SHA-256 against manifest.json before a run. The two #1004 notes
come from Python's `random` (seeded; random(), choice() and randint() are stable across 3.x), so
the unit test pins their hashes too.
"""
import hashlib
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

WORDS = (
    "garden river lantern harbor quiet orbit meadow copper signal violet pattern ledger compass winter "
    "thread canvas marble echo summit willow cedar ember glacier atlas prism falcon harvest beacon "
    "tide quarry cobalt saffron basalt meridian solstice tundra fjord delta cascade horizon"
).split()


def corpus_1004():
    """(Long-10k.md, Long-LP-700.md) as bytes. The 2,000 notes of the original vault are not
    written, but their random draws are made: the long notes follow them in the sequence."""
    random.seed(42)
    words = WORDS
    folders = ["Archive/%02d" % i for i in range(20)] + ["Notes/%s" % w for w in words[:20]]
    names = []
    for i in range(2000):
        names.append("%s/note-%04d-%s" % (folders[i % len(folders)], i, random.choice(words)))

    def para(n):
        return " ".join(random.choice(words) for _ in range(n)).capitalize() + "."

    def base(name):
        return name.rsplit("/", 1)[-1]

    for _ in names:
        random.choice(words), random.choice(words)  # the note's two tags
        for _ in range(random.randint(3, 12)):
            para(3)
            for _ in range(random.randint(1, 4)):
                para(random.randint(15, 60))
                if random.random() < 0.3:
                    random.choice(names)
            if random.random() < 0.3:
                para(5), para(4), para(6)
    # 10k-line mixed note
    L = ["# Long note 10k", ""]
    k = 0
    while len(L) < 10000:
        k += 1
        L += ["## Section %d %s" % (k, para(3)[:-1]), ""]
        L += [para(random.randint(20, 50)) + (" **bold %s** and *italic* and `code`." % random.choice(words)) for _ in range(6)]
        L += ["", "- item one [[%s]]" % base(random.choice(names)), "- item two #%s" % random.choice(words),
              "  - nested item", "", "```rust", "fn section_%d() -> u32 { %d }" % (k, k), "```", "",
              "| a | b | c |", "|---|---|---|", "| %s | %s | %d |" % (random.choice(words), random.choice(words), k), "",
              "> " + para(12), ""]
    return (("\n".join(L[:10000]) + "\n").encode(),
            ("# Long LP 700\n" + "\n".join(L[1:700]) + "\n").encode())


def big_note():
    """Byte for byte what scroll-frametime.ps1 writes (see its here-string generator)."""
    out = []
    for i in range(1, 1501):
        out += [f"## Section {i}", ""]
        out += [f"Paragraph {i} with **bold**, *italic*, `code` and a [[link {i}]]. " * 3, ""]
        out += [f"- item one of {i}", f"- item two with a longer line of text {i}", f"- [ ] task {i}", ""]
        out += ["```rust", f"fn section_{i}() -> u32 {{ {i} }}", "```", ""]
        out += ["| a | b |", "|---|---|", f"| {i} | {i * 2} |", ""]
    return ("\r\n".join(out) + "\r\n").encode()


def notes():
    long_10k, long_700 = corpus_1004()
    # 20 lines: scrolling must not depend on the note at all if the cost is not the note's.
    tiny = b"".join(long_700.splitlines(keepends=True)[:20])
    big = big_note()
    head = b"".join(big.splitlines(keepends=True)[:320])
    return {"big-24k.md": big, "big-head-320.md": head, "Long-10k.md": long_10k, "Long-LP-700.md": long_700,
            "Tiny-20.md": tiny}


def describe(data):
    text = data.decode()
    return {
        "bytes": len(data),
        "lines": text.count("\n"),
        "headings": sum(1 for line in text.splitlines() if line.startswith("#")),
        "sha256": hashlib.sha256(data).hexdigest(),
    }


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name, data in notes().items():
        (out / name).write_bytes(data)
        manifest[name] = describe(data)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    for name, info in manifest.items():
        print(f"{name:15} {info['lines']:6} lines {info['headings']:5} headings {info['bytes']:8} bytes {info['sha256'][:16]}")
    if "--check" in sys.argv:
        expected = json.loads((HERE / "manifest.json").read_text())
        if expected != manifest:
            sys.exit("notes differ from scripts/perf/scroll/manifest.json")
        print("matches manifest.json")


if __name__ == "__main__":
    main()
